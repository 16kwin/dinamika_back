package com.example.dinamika_back.features;

/**
 * Честный уровень отключения функции (раздел 3.1 проекта). В реестре — уровень, которого функция достигает
 * при выключении потолком; фактический уровень печатает отчёт «Профиль безопасности» (B6).
 */
public enum FeatureLevel {

    /** Функция есть только во фронтенде либо данные уже у клиента (скачивание при разрешённом просмотре) */
    L1("скрыто в интерфейсе"),
    /** Бины есть, ворота отвечают 404 до Spring Security на все методы правила; сторож запрещает побочные эффекты */
    L2("маршрут закрыт"),
    /** Бины не созданы: нет эндпоинтов, потоков, процессов, клиентов */
    L3("код не загружен"),
    /** Кода модуля нет в поставке (вариант сборки) */
    L4("нет в поставке");

    private final String title;

    FeatureLevel(String title) {
        this.title = title;
    }

    public String title() {
        return title;
    }
}
